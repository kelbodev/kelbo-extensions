// Oracle attraverso la sezione Database di Kelbo. Server da KELBO_TEST_ORACLE="host:porta:servizio:utente:password"
// (es. un container gvenzl/oracle-free con APP_USER); senza, i test che lo usano vengono saltati.
const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const path = require('path');
const { startServer, i18nProblems } = require('kelbo/testkit');

const DIR = path.join(__dirname, '..');
const target = process.env.KELBO_TEST_ORACLE
  ? (([host, port, database, user, ...pw]) => ({ host, port: Number(port), database, user, password: pw.join(':') }))(process.env.KELBO_TEST_ORACLE.split(':'))
  : null;
const SCHEMA = target ? target.user.toUpperCase() : '';
let srv;
const api = (m, p, body) => srv.request(m, `${p.startsWith('/core') ? '/api' : '/api/ext/db-client'}${p}`, body !== undefined ? { body } : {});
const run = (sql, extra = {}) => api('POST', '/connections/ora/query', { sql, ...extra });
async function confirmed(sql, extra = {}) {
  const first = await run(sql, extra);
  assert.equal(first.status, 428, first.text);
  return run(sql, { ...extra, confirm: first.json.token });
}

before(async () => {
  srv = await startServer({ projects: [] }, { install: [DIR] });
  if (!target) return;
  await api('POST', '/core/vault/init', { password: 'master-password-ora' });
  await api('POST', '/connections', { id: 'ora', label: 'Oracle', type: 'oracle', ...target, options: { connectBy: 'service' } });
  // schema pulito: via le tabelle lasciate da un giro precedente
  await confirmed(`BEGIN
  FOR t IN (SELECT table_name FROM user_tables) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE "' || t.table_name || '" CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;`);
});
after(() => srv?.stop());

test('traduzioni', () => assert.deepEqual(i18nProblems(DIR), []));

test('connessione, schemi, query, PL/SQL, conferme, errori', async t => {
  if (!target) return t.skip('KELBO_TEST_ORACLE non impostata');
  let r = await api('POST', '/connections/ora/test', {});
  assert.equal(r.status, 200, r.text);
  assert.match(r.json.version, /^Oracle \d+/);
  assert.equal(r.json.user, SCHEMA);
  r = await confirmed(`CREATE TABLE clienti (id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_clienti PRIMARY KEY,
    nome VARCHAR2(80 CHAR) NOT NULL, citta VARCHAR2(60 CHAR), creato DATE DEFAULT DATE '2026-01-02' NOT NULL, foto BLOB, note CLOB, attivo NUMBER(1) DEFAULT 1 NOT NULL);`);
  assert.equal(r.status, 200, r.text);
  r = await confirmed("INSERT INTO clienti (nome, citta, foto, note) SELECT 'Giulia', 'Milano', HEXTORAW('DEADBEEF'), 'q''[x]''' FROM dual UNION ALL SELECT 'Marco', 'Torino', NULL, NULL FROM dual UNION ALL SELECT 'Sara', NULL, NULL, NULL FROM dual");
  assert.equal(r.json.affectedRows, 3, r.text);
  // blocco PL/SQL con ";" interni e "/" come separatore, insieme a una SELECT
  r = await confirmed(`BEGIN\n  UPDATE clienti SET attivo = 0 WHERE nome = 'Sara';\nEND;\n/\nSELECT COUNT(*) AS n FROM clienti WHERE attivo = 0`);
  assert.equal(r.status, 200, r.text);
  r = await api('GET', '/connections/ora/databases');
  assert.equal(r.json.databases[0], SCHEMA);
  assert.equal(r.json.default, SCHEMA);
  assert.deepEqual((await api('GET', `/connections/ora/databases/${SCHEMA}/tables`)).json.tables.map(x => x.name), ['CLIENTI']);
  r = await run("SELECT id, nome, creato, foto, attivo FROM clienti WHERE nome <> q'[x]' ORDER BY id;", { limit: 2 });
  assert.equal(r.status, 200, r.text);
  assert.deepEqual([r.json.rowCount, r.json.truncated, r.json.total], [2, true, 3]);
  assert.deepEqual(r.json.rows[0], [1, 'Giulia', '2026-01-02 00:00:00', '0xdeadbeef', 1]);
  r = await run('SELECT * FROM nope');
  assert.equal(r.json.code, 'db-client.database');
  assert.equal(r.json.params.dbCode, 'ORA-00942');
  assert.equal((await run('SELECT seq.NEXTVAL FROM dual')).status, 428);
});

test('dati, export, designer', async t => {
  if (!target) return t.skip('KELBO_TEST_ORACLE non impostata');
  const base = `/connections/ora/databases/${SCHEMA}`;
  let r = await api('POST', `${base}/tables/CLIENTI/rows`, { page: 1, pageSize: 25, search: 'MIL' });
  assert.equal(r.status, 200, r.text);
  assert.deepEqual([r.json.total, r.json.rows.length], [1, 1]);
  const edit = body => api('POST', `${base}/tables/CLIENTI/row`, body);
  r = await edit({ op: 'update', key: { ID: 2 }, values: { CITTA: "Aosta d'Italia" } });
  assert.equal(r.json.sql, `UPDATE "${SCHEMA}"."CLIENTI" SET "CITTA" = 'Aosta d''Italia' WHERE "ID" = 2 AND ROWNUM = 1`);
  r = await edit({ op: 'update', key: { ID: 2 }, values: { CITTA: "Aosta d'Italia" }, confirm: r.json.token });
  assert.equal(r.json.affectedRows, 1, r.text);
  r = await api('POST', '/connections/ora/exports', { format: 'sql', source: { type: 'table', db: SCHEMA, table: 'CLIENTI' } });
  const file = await srv.request('GET', `/api/ext/db-client/connections/ora/exports/${r.json.id}`);
  assert.match(file.text, /CREATE TABLE "[A-Z]+"\."CLIENTI"/);
  assert.match(file.text, /HEXTORAW\('deadbeef'\)/i);
  const def = (await api('GET', `${base}/tables/CLIENTI/definition`)).json.definition;
  assert.deepEqual(def.primaryKey, ['ID']);
  const byName = Object.fromEntries(def.columns.map(x => [x.name, x]));
  assert.deepEqual([byName.ID.type, byName.ID.autoIncrement, byName.NOME.type, byName.NOME.length, byName.NOME.nullable], ['NUMBER', true, 'VARCHAR2', 80, false]);
  assert.deepEqual(byName.ATTIVO.default, { kind: 'value', value: '1' });
  // modifica: rinomina e allarga una colonna, nuovo default, nuova colonna con commento
  const next = { ...def, columns: [...def.columns.map(x => (x.name === 'CITTA' ? { ...x, name: 'LUOGO', length: 120, default: { kind: 'value', value: 'N/D' } } : x)),
    { name: 'EXTRA', type: 'VARCHAR2', length: 20, nullable: true, comment: 'Nota breve' }] };
  const design = { table: 'CLIENTI', definition: next, renames: { LUOGO: 'CITTA' } };
  r = await api('POST', `${base}/migrate`, { design });
  assert.equal(r.status, 428, r.text);
  r = await api('POST', `${base}/migrate`, { design, confirm: r.json.token, acknowledgeWarnings: true });
  assert.equal(r.status, 200, r.text);
  const after = (await api('GET', `${base}/tables/CLIENTI/definition`)).json.definition;
  const a = Object.fromEntries(after.columns.map(x => [x.name, x]));
  assert.deepEqual([a.LUOGO.length, a.LUOGO.default, a.EXTRA.comment, a.NOME.nullable], [120, { kind: 'value', value: 'N/D' }, 'Nota breve', false]);
  // il designer crea una tabella nuova con una chiave esterna
  const definition = { name: 'ORDINI', primaryKey: ['ID'], columns: [{ name: 'ID', type: 'NUMBER', length: 10, autoIncrement: true },
    { name: 'CLIENTE', type: 'NUMBER', length: 10, nullable: false }, { name: 'QUANDO', type: 'TIMESTAMP', nullable: true, default: { kind: 'current_timestamp' } }],
  foreignKeys: [{ name: 'FK_ORDINI_CLIENTE', columns: ['CLIENTE'], refTable: 'CLIENTI', refColumns: ['ID'], onDelete: 'CASCADE' }] };
  r = await api('POST', `${base}/create-table`, { definition });
  assert.equal(r.status, 428, r.text);
  r = await api('POST', `${base}/create-table`, { definition, confirm: r.json.token });
  assert.equal(r.status, 200, r.text);
  const ordini = (await api('GET', `${base}/tables/ORDINI/definition`)).json.definition;
  assert.deepEqual(ordini.foreignKeys.map(f => [f.name, f.refTable, f.onDelete]), [['FK_ORDINI_CLIENTE', 'CLIENTI', 'CASCADE']]);
});

test('strumenti MCP: solo letture in una transazione READ ONLY', async t => {
  if (!target) return t.skip('KELBO_TEST_ORACLE non impostata');
  const { mcpClient } = require('kelbo/testkit');
  const client = await mcpClient(srv);
  try {
    let r = await client.callTool({ name: 'db_client_query', arguments: { connection: 'ora', sql: 'SELECT COUNT(*) AS n FROM clienti' } });
    assert.equal(r.isError, undefined, JSON.stringify(r.content));
    r = await client.callTool({ name: 'db_client_tables', arguments: { connection: 'ora' } });
    assert.equal(r.structuredContent.database, SCHEMA);
    r = await client.callTool({ name: 'db_client_query', arguments: { connection: 'ora', sql: 'DELETE FROM clienti' } });
    assert.equal(r.structuredContent.code, 'db-client.mcp_read_only');
  } finally { await client.close(); }
});
