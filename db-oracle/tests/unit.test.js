// Oracle senza server: classificazione, blocchi PL/SQL, conteggio, paginazione, DDL e operazioni
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { dbClientTools } = require('kelbo/testkit');
const createOracleEngine = require('../engine');
const ddl = require('../ddl');

const engine = createOracleEngine(dbClientTools());
const c = s => engine.sql.classify(s);

test('classificazione', () => {
  for (const s of ['SELECT 1 FROM dual', 'SELECT * FROM "T" FETCH FIRST 10 ROWS ONLY', "SELECT q'[drop table x; ]' FROM dual",
    'WITH a AS (SELECT 1 AS x FROM dual) SELECT * FROM a', 'SELECT "UPDATE" FROM t', "SELECT REPLACE(a, 'x', 'y') FROM t;"]) assert.equal(c(s).kind, 'read', s);
  for (const s of ['INSERT INTO t VALUES (1)', 'MERGE INTO t USING s ON (1 = 1) WHEN MATCHED THEN UPDATE SET a = 1', 'BEGIN NULL; END;',
    'DECLARE x NUMBER; BEGIN x := 1; END;', 'CREATE OR REPLACE PROCEDURE p AS BEGIN NULL; END;', 'xyz']) assert.equal(c(s).kind, 'write', s);
  assert.equal(c('SELECT seq.NEXTVAL FROM dual').reason, 'write_function');
  assert.equal(c('SELECT * FROM t FOR UPDATE').reason, 'row_lock');
  assert.equal(c('SELECT a INTO x FROM t').reason, 'into');
  assert.equal(c('SELECT 1 FROM dual; SELECT 2 FROM dual').kind, 'invalid');
});

test('istruzioni: ";" per l\'SQL, "/" dopo i blocchi PL/SQL', () => {
  const text = "SELECT ';' FROM dual;\nINSERT INTO t VALUES (1);\nBEGIN\n  UPDATE t SET a = 2;\n  COMMIT;\nEND;\n/\nCREATE OR REPLACE TRIGGER tr BEFORE INSERT ON t FOR EACH ROW BEGIN :new.a := 1; END;\n/\nSELECT 2 FROM dual";
  const parts = engine.sql.splitStatements(text);
  assert.deepEqual(parts.map(p => p.sql), ["SELECT ';' FROM dual", 'INSERT INTO t VALUES (1)', 'BEGIN\n  UPDATE t SET a = 2;\n  COMMIT;\nEND;',
    'CREATE OR REPLACE TRIGGER tr BEFORE INSERT ON t FOR EACH ROW BEGIN :new.a := 1; END;', 'SELECT 2 FROM dual']);
  for (const p of parts) assert.equal(text.slice(p.start, p.start + p.sql.length), p.sql);
});

test('conteggio senza "AS" nell\'alias, paginazione, ricerca, segnaposto, letterali', () => {
  assert.deepEqual(engine.sql.countQuery('SELECT * FROM t OFFSET 10 ROWS FETCH NEXT 5 ROWS ONLY'), { sql: 'SELECT COUNT(*) FROM (\nSELECT * FROM t\n) kelbo_count', limit: { count: 5, offset: 10 } });
  assert.deepEqual(engine.page('SELECT * FROM t', [], 25, 50), { sql: 'SELECT * FROM t OFFSET ? ROWS FETCH NEXT ? ROWS ONLY', params: [50, 25] });
  assert.equal(engine.search('"NOME"'), 'UPPER(TO_CHAR("NOME")) LIKE UPPER(?)');
  assert.equal(engine.sql.bindParams('SELECT * FROM t WHERE a = ? AND b = :b', { '#1': "o'k", b: 3 }).sql, "SELECT * FROM t WHERE a = 'o''k' AND b = 3");
  assert.equal(engine.literal(Buffer.from([0xca, 0xfe])), "HEXTORAW('cafe')");
  assert.equal(engine.literal(true), '1');
  assert.equal(engine.defaultSchema({ user: 'kelbo' }), 'KELBO');
  assert.deepEqual(engine.sql.schemaChange('ALTER TABLE "S"."T" RENAME COLUMN a TO b'), { table: 'T', operation: 'rename_a' });
  assert.deepEqual(engine.sql.schemaChange('ALTER TABLE t MODIFY (nome VARCHAR2(10))'), { table: 't', operation: 'modify_nome' });
  assert.equal(engine.errorInfo({ message: 'ORA-00942: x', code: 'ORA-00942' }).code, 'ORA-00942');
});

test('DDL: identity, default prima di NOT NULL, commenti, chiavi esterne', () => {
  const [create, ...rest] = ddl.createTableStatements('KELBO', {
    name: 'ORDINI', comment: 'Ordini', primaryKey: ['ID'],
    columns: [{ name: 'ID', type: 'NUMBER', length: 10, autoIncrement: true }, { name: 'NOME', type: 'VARCHAR2', length: 80, nullable: false, default: { kind: 'value', value: "l'x" } },
      { name: 'CREATO', type: 'TIMESTAMP', length: 3, nullable: false, default: { kind: 'current_timestamp' } }, { name: 'D', type: 'DATE', nullable: true, default: { kind: 'current_timestamp' }, comment: 'Giorno' }],
    indexes: [{ name: 'IX_NOME', columns: ['NOME'], unique: true }],
    foreignKeys: [{ name: 'FK_X', columns: ['ID'], refTable: 'ALTRA', refColumns: ['ID'], onDelete: 'SET NULL' }],
  });
  assert.equal(create, `CREATE TABLE "KELBO"."ORDINI" (
  "ID" NUMBER(10,0) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  "NOME" VARCHAR2(80 CHAR) DEFAULT 'l''x' NOT NULL,
  "CREATO" TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  "D" DATE DEFAULT SYSDATE,
  CONSTRAINT "PK_ORDINI" PRIMARY KEY ("ID"),
  CONSTRAINT "FK_X" FOREIGN KEY ("ID") REFERENCES "KELBO"."ALTRA" ("ID") ON DELETE SET NULL
)`);
  assert.deepEqual(rest, ['CREATE UNIQUE INDEX "KELBO"."IX_NOME" ON "KELBO"."ORDINI" ("NOME")', `COMMENT ON TABLE "KELBO"."ORDINI" IS 'Ordini'`,
    `COMMENT ON COLUMN "KELBO"."ORDINI"."D" IS 'Giorno'`]);
  assert.throws(() => ddl.columnSql({ name: 'A', type: 'NUMBER', unsigned: true }), /unsigned/);
  assert.throws(() => ddl.createTableStatements('S', { name: 'T', columns: [{ name: 'A', type: 'NUMBER' }], foreignKeys: [{ columns: ['A'], refTable: 'U', refColumns: ['A'], onUpdate: 'CASCADE' }] }), /fk_action/);
});

test('MODIFY ripete solo ciò che cambia (ORA-01442/ORA-01451)', () => {
  const before = { tables: { T: { columns: [{ name: 'A', type: 'VARCHAR2', length: 20, nullable: false, default: { kind: 'none' } }], primaryKey: [], indexes: [], foreignKeys: [] } } };
  const after = { tables: { T: { columns: [{ name: 'A', type: 'VARCHAR2', length: 40, nullable: false, default: { kind: 'none' } }], primaryKey: [], indexes: [], foreignKeys: [] } } };
  const { ops } = engine.schema.diff(before, after, {});
  assert.deepEqual(engine.schema.statements('S', ops), ['ALTER TABLE "S"."T" MODIFY ("A" VARCHAR2(40 CHAR))']);
  const renamed = { tables: { T: { ...after.tables.T, columns: [{ ...after.tables.T.columns[0], name: 'B', length: 20, nullable: true }] } } };
  assert.deepEqual(engine.schema.statements('S', engine.schema.diff(before, renamed, { 'T.B': 'A' }).ops),
    ['ALTER TABLE "S"."T" RENAME COLUMN "A" TO "B"', 'ALTER TABLE "S"."T" MODIFY ("B" NULL)']);
  assert.deepEqual(engine.schema.statements('S', [{ op: 'rename_table', table: 'T', to: 'U' }, { op: 'drop_primary_key', table: 'U' }]),
    ['ALTER TABLE "S"."T" RENAME TO "U"', 'ALTER TABLE "S"."U" DROP PRIMARY KEY']);
});
