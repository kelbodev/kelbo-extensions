// PostgreSQL attraverso la sezione Database di Kelbo (db-client + questo motore), contro un
// server usa e getta (saltati se PostgreSQL non è installato)
const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const path = require('path');
const { startServer, i18nProblems } = require('kelbo/testkit');
const { startPostgres } = require('./pg');

const DIR = path.join(__dirname, '..');
let pg, srv;
before(async () => {
  pg = await startPostgres();
  srv = await startServer({ projects: [] }, { install: [DIR] });
  if (!pg) return;
  await pg.query(`CREATE TABLE clienti (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome varchar(80) NOT NULL, citta text,
    creato timestamptz NOT NULL DEFAULT now(), dati jsonb, foto bytea, tag text[])`);
  await pg.query(`INSERT INTO clienti (nome, citta, dati, foto, tag) VALUES ('Giulia', 'Milano', '{"vip":true}', '\\xdeadbeef', '{a,b}'),
    ('Marco', 'Torino', NULL, NULL, NULL), ('Sara', NULL, NULL, NULL, NULL)`);
  await pg.query('CREATE SCHEMA magazzino');
  await pg.query('CREATE TABLE magazzino.articoli (codice text PRIMARY KEY, qta integer NOT NULL DEFAULT 0)');
  await pg.query('CREATE VIEW vista_milano AS SELECT * FROM clienti WHERE citta = \'Milano\'');
});
after(async () => { await srv?.stop(); pg?.stop(); });

const api = (m, p, body) => srv.request(m, `${p.startsWith('/core') ? '/api' : '/api/ext/db-client'}${p}`, body !== undefined ? { body } : {});
const run = (sql, extra = {}) => api('POST', '/connections/pg/query', { sql, ...extra });
async function confirmed(sql, extra = {}) {
  const first = await run(sql, extra);
  assert.equal(first.status, 428, first.text);
  return run(sql, { ...extra, confirm: first.json.token });
}

test('traduzioni', () => assert.deepEqual(i18nProblems(DIR), []));

test('motore offerto alla sezione Database', async () => {
  const info = (await api('GET', '/info')).json;
  const e = info.engines.find(x => x.id === 'postgres');
  assert.equal(e.extension, 'db-postgres');
  assert.equal(e.connection.defaultPort, 5432);
  assert.equal(e.dialect.schemas, true);
  assert.equal(e.dialect.quote, '"');
});

test('connessione, schemi, tabelle, query e conferme', async t => {
  if (!pg) return t.skip('PostgreSQL non installato');
  await api('POST', '/core/vault/init', { password: 'master-password-pg' });
  let r = await api('POST', '/connections', { id: 'pg', label: 'PG', type: 'postgres', host: '127.0.0.1', port: pg.port, user: pg.user, password: pg.password, database: 'shop' });
  assert.equal(r.status, 200, r.text);
  assert.equal(r.json.connection.defaultDb, 'public');
  r = await api('POST', '/connections/pg/test', {});
  assert.equal(r.status, 200, r.text);
  assert.match(r.json.version, /^PostgreSQL 1\d/);
  assert.equal(r.json.db, 'shop');
  // schemi al posto dei database, public per primo
  r = await api('GET', '/connections/pg/databases');
  assert.equal(r.json.databases[0], 'public');
  assert.ok(r.json.databases.includes('magazzino'));
  assert.deepEqual([r.json.default, r.json.schemas], ['public', true]);
  const tables = (await api('GET', '/connections/pg/databases/public/tables')).json.tables;
  assert.deepEqual(tables.map(x => [x.name, x.view]), [['clienti', false], ['vista_milano', true]]);
  assert.deepEqual((await api('GET', '/connections/pg/databases/magazzino/tables')).json.tables.map(x => x.name), ['articoli']);
  // lettura: tipi resi come testo/JSON, origine delle colonne per la modifica
  r = await run('SELECT id, nome, creato, dati, foto, tag FROM clienti ORDER BY id');
  assert.equal(r.status, 200, r.text);
  assert.equal(r.json.statement, 'read');
  assert.equal(r.json.total, 3);
  assert.deepEqual(r.json.columns.slice(0, 2).map(c => [c.name, c.db, c.table, c.column]), [['id', 'public', 'clienti', 'id'], ['nome', 'public', 'clienti', 'nome']]);
  const [first] = r.json.rows;
  assert.equal(typeof first[2], 'string');
  assert.equal(first[3], '{"vip":true}');
  assert.equal(first[4], '0xdeadbeef');
  assert.equal(first[5], '["a","b"]');
  // search_path dello schema scelto
  r = await run('SELECT codice FROM articoli', { database: 'magazzino' });
  assert.equal(r.status, 200, r.text);
  // limite di righe e conteggio senza limiti
  r = await run('SELECT * FROM generate_series(1, 50) LIMIT 20', { limit: 5 });
  assert.deepEqual([r.json.rowCount, r.json.truncated, r.json.total, r.json.queryLimit], [5, true, 50, { count: 20, offset: 0 }]);
  // scritture solo con conferma; funzioni con effetti trattate come scritture
  r = await run("SELECT nextval('clienti_id_seq')");
  assert.equal(r.status, 428);
  assert.equal(r.json.reason, 'write_function');
  r = await confirmed("UPDATE clienti SET citta = 'Roma' WHERE nome = 'Sara'");
  assert.equal(r.status, 200, r.text);
  assert.equal(r.json.affectedRows, 1);
  // errore del database: messaggio e codice SQLSTATE
  r = await run('SELECT * FROM non_esiste');
  assert.equal(r.json.code, 'db-client.database');
  assert.equal(r.json.params.dbCode, '42P01');
  // più istruzioni sulla stessa sessione
  r = await confirmed("CREATE TEMP TABLE tmp (a int); INSERT INTO tmp VALUES (1), (2); SELECT count(*) FROM tmp");
  assert.equal(r.json.kind, 'batch', r.text);
  assert.equal(r.json.failed, null);
  assert.equal(String(r.json.results[2].rows[0][0]), '2');
});

test('dati: anteprima, ricerca, modifica, eliminazione, export', async t => {
  if (!pg) return t.skip('PostgreSQL non installato');
  let r = await api('POST', '/connections/pg/databases/public/tables/clienti/rows', { page: 1, pageSize: 25, search: 'mil', sort: { column: 'id', dir: 'asc' } });
  assert.equal(r.status, 200, r.text);
  assert.deepEqual([r.json.total, r.json.primaryKey], [1, ['id']]);
  const edit = body => api('POST', '/connections/pg/databases/public/tables/clienti/row', body);
  r = await edit({ op: 'update', key: { id: 2 }, values: { citta: "Aosta d'Italia" } });
  assert.equal(r.status, 428);
  assert.match(r.json.sql, /UPDATE "public"."clienti" SET "citta" = 'Aosta d''Italia' WHERE "id" = 2/);
  r = await edit({ op: 'update', key: { id: 2 }, values: { citta: "Aosta d'Italia" }, confirm: r.json.token });
  assert.equal(r.status, 200, r.text);
  r = await edit({ op: 'insert', values: { nome: 'Luca' } });
  r = await edit({ op: 'insert', values: { nome: 'Luca' }, confirm: r.json.token });
  assert.equal(r.json.affectedRows, 1, r.text);
  r = await edit({ op: 'delete-many', keys: [{ id: 3 }, { id: 4 }] });
  assert.match(r.json.sql, /DELETE FROM "public"."clienti" WHERE "id" IN \(3, 4\)/);
  r = await edit({ op: 'delete-many', keys: [{ id: 3 }, { id: 4 }], confirm: r.json.token });
  assert.equal(r.json.affectedRows, 2, r.text);
  // export SQL con la struttura ricostruita
  r = await api('POST', '/connections/pg/exports', { format: 'sql', source: { type: 'table', db: 'public', table: 'clienti' } });
  assert.equal(r.status, 200, r.text);
  const file = await srv.request('GET', `/api/ext/db-client/connections/pg/exports/${r.json.id}`);
  assert.match(file.text, /CREATE TABLE "public"."clienti"/);
  assert.match(file.text, /INSERT INTO "clienti" \("id", "nome", "citta", "creato", "dati", "foto", "tag"\) VALUES/);
  assert.match(file.text, /'\\xdeadbeef'::bytea/);
  r = await api('POST', '/connections/pg/exports', { format: 'csv', source: { type: 'query', sql: 'SELECT id, nome FROM clienti ORDER BY id' } });
  const csv = await srv.request('GET', `/api/ext/db-client/connections/pg/exports/${r.json.id}`);
  assert.match(csv.text, /^id,nome\r\n1,Giulia\r\n2,Marco\r\n/);
});

test('designer: struttura, creazione e modifica di una tabella', async t => {
  if (!pg) return t.skip('PostgreSQL non installato');
  let r = await api('GET', '/connections/pg/databases/public/tables/clienti/definition');
  assert.equal(r.status, 200, r.text);
  const def = r.json.definition;
  assert.deepEqual(def.primaryKey, ['id']);
  const byName = Object.fromEntries(def.columns.map(c => [c.name, c]));
  assert.deepEqual([byName.id.type, byName.id.autoIncrement], ['INTEGER', true]);
  assert.deepEqual([byName.nome.type, byName.nome.length, byName.nome.nullable], ['VARCHAR', 80, false]);
  assert.deepEqual(byName.creato.default, { kind: 'current_timestamp' });
  assert.equal(byName.tag.unsupported, 'text[]');
  // nuova tabella dal designer
  const definition = { name: 'ordini', comment: 'Ordini', columns: [
    { name: 'id', type: 'BIGINT', autoIncrement: true, nullable: false },
    { name: 'cliente', type: 'INTEGER', nullable: false },
    { name: 'totale', type: 'NUMERIC', length: 10, scale: 2, nullable: false, default: { kind: 'value', value: '0' } },
  ], primaryKey: ['id'], indexes: [{ name: 'ix_ordini_cliente', columns: ['cliente'] }],
  foreignKeys: [{ name: 'fk_ordini_cliente', columns: ['cliente'], refTable: 'clienti', refColumns: ['id'], onDelete: 'CASCADE' }] };
  r = await api('POST', '/connections/pg/databases/public/create-table', { definition });
  assert.equal(r.status, 428, r.text);
  r = await api('POST', '/connections/pg/databases/public/create-table', { definition, confirm: r.json.token });
  assert.equal(r.status, 200, r.text);
  const info = (await api('GET', '/connections/pg/databases/public/tables/ordini')).json;
  assert.deepEqual(info.foreignKeys.map(f => [f.name, f.refTable]), [['fk_ordini_cliente', 'clienti']]);
  assert.ok(info.indexes.some(i => i.name === 'ix_ordini_cliente'));
  // modifica: nuova colonna, tipo più largo, rinomina (il confronto lo fa il db-client)
  const current = (await api('GET', '/connections/pg/databases/public/tables/ordini/definition')).json.definition;
  const next = { ...current, columns: [...current.columns.map(c => (c.name === 'totale' ? { ...c, name: 'importo', length: 12 } : c)), { name: 'note', type: 'TEXT', nullable: true }] };
  const design = { table: 'ordini', definition: next, renames: { importo: 'totale' } };
  r = await api('POST', '/connections/pg/databases/public/migrate', { design });
  assert.equal(r.status, 428, r.text);
  assert.ok(r.json.statements.some(s => /RENAME COLUMN "totale" TO "importo"/.test(s)), r.json.sql);
  r = await api('POST', '/connections/pg/databases/public/migrate', { design, confirm: r.json.token, acknowledgeWarnings: true });
  assert.equal(r.status, 200, r.text);
  const after = (await api('GET', '/connections/pg/databases/public/tables/ordini/definition')).json.definition;
  assert.deepEqual(after.columns.map(c => c.name), ['id', 'cliente', 'importo', 'note']);
  assert.equal(after.columns[2].length, 12);
});

test('strumenti MCP: solo letture in una transazione di sola lettura', async t => {
  if (!pg) return t.skip('PostgreSQL non installato');
  const { mcpClient } = require('kelbo/testkit');
  const client = await mcpClient(srv);
  try {
    let r = await client.callTool({ name: 'db_client_query', arguments: { connection: 'pg', sql: 'SELECT count(*) AS n FROM clienti' } });
    assert.equal(r.isError, undefined, JSON.stringify(r.content));
    r = await client.callTool({ name: 'db_client_tables', arguments: { connection: 'pg' } });
    assert.equal(r.structuredContent.database, 'public');
    r = await client.callTool({ name: 'db_client_query', arguments: { connection: 'pg', sql: 'DELETE FROM clienti' } });
    assert.equal(r.structuredContent.code, 'db-client.mcp_read_only');
  } finally { await client.close(); }
});
