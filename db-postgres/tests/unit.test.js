// PostgreSQL senza server: classificazione, segnaposto, conteggio, DDL e operazioni del designer
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { dbClientTools } = require('kelbo/testkit');
const createPgEngine = require('../engine');
const ops = require('../ops');
const ddl = require('../ddl');

const engine = createPgEngine(dbClientTools());
const kind = s => engine.sql.classify(s).kind;

test('classificazione: letture, scritture, casi di PostgreSQL', () => {
  for (const s of ['SELECT 1', "select 'drop table x' as t", 'WITH a AS (SELECT 1) SELECT * FROM a', 'SHOW search_path',
    'EXPLAIN SELECT * FROM t', 'TABLE t', 'VALUES (1), (2)', 'SELECT $$ DELETE FROM x $$', "SELECT E'it\\'s ; delete'",
    'SELECT "update" FROM t', 'SELECT now()::date', 'SELECT replace(a, \'x\', \'y\') FROM t']) {
    assert.equal(kind(s), 'read', s);
  }
  for (const s of ['INSERT INTO t VALUES (1)', 'UPDATE t SET a = 1', 'DELETE FROM t', 'MERGE INTO t USING s ON true WHEN MATCHED THEN DELETE',
    'CREATE TABLE x (a int)', 'COPY t TO STDOUT', 'DO $$ BEGIN END $$', 'VACUUM', 'SET search_path TO x', 'CALL p()', 'BEGIN', 'unknown thing']) {
    assert.equal(kind(s), 'write', s);
  }
  assert.deepEqual(engine.sql.classify('SELECT nextval(\'s\')'), { kind: 'write', verb: 'SELECT', reason: 'write_function', word: 'nextval' });
  assert.equal(engine.sql.classify('SELECT pg_terminate_backend(1)').reason, 'write_function');
  assert.equal(engine.sql.classify('SELECT * INTO nuova FROM t').reason, 'into');
  assert.equal(engine.sql.classify('SELECT * FROM t FOR NO KEY UPDATE').reason, 'row_lock');
  assert.equal(engine.sql.classify('WITH d AS (DELETE FROM t RETURNING *) SELECT * FROM d').reason, 'write_word');
  assert.equal(engine.sql.classify('EXPLAIN ANALYZE DELETE FROM t').reason, 'explain_analyze_write');
  assert.equal(kind('EXPLAIN ANALYZE SELECT 1'), 'read');
  assert.equal(engine.sql.classify('SELECT 1; SELECT 2').reason, 'single_statement');
});

test('istruzioni, segnaposto e conteggio con le regole di PostgreSQL', () => {
  assert.deepEqual(engine.sql.splitStatements("SELECT 1; SELECT $f$ a;b $f$; SELECT ';'").map(s => s.sql), ['SELECT 1', 'SELECT $f$ a;b $f$', "SELECT ';'"]);
  assert.deepEqual(engine.sql.describeParams('SELECT * FROM t WHERE id = ? AND x::text = :nome').map(p => p.name), ['id', 'nome']);
  assert.equal(engine.sql.bindParams("SELECT ? AS a, ? AS b", { '#1': "o'k", '#2': null }).sql, "SELECT 'o''k' AS a, NULL AS b");
  assert.deepEqual(engine.sql.countQuery('SELECT * FROM t LIMIT 10 OFFSET 5'), { sql: 'SELECT COUNT(*) FROM (\nSELECT * FROM t\n) AS kelbo_count', limit: { count: 10, offset: 5 } });
  assert.deepEqual(engine.sql.schemaChange('ALTER TABLE public.ordini ADD COLUMN note text'), { table: 'ordini', operation: 'add_note' });
  assert.deepEqual(engine.sql.schemaChange('CREATE UNIQUE INDEX ix_email ON "clienti" (email)'), { table: 'clienti', operation: 'add_index_ix_email' });
  assert.deepEqual(engine.sql.schemaChange('ALTER TABLE t ALTER COLUMN a TYPE bigint'), { table: 't', operation: 'modify_a' });
});

test('DDL: create table con identity, indici e commenti; tipi e opzioni non di PostgreSQL rifiutati', () => {
  const statements = ddl.createTableStatements('app', {
    name: 'ordini', comment: 'Ordini',
    columns: [
      { name: 'id', type: 'INT', autoIncrement: true },
      { name: 'cliente', type: 'VARCHAR', length: 80, nullable: false, comment: "Nome dell'utente" },
      { name: 'totale', type: 'NUMERIC', length: 10, scale: 2, nullable: false, default: { kind: 'value', value: '0' } },
      { name: 'creato', type: 'TIMESTAMPTZ', nullable: false, default: { kind: 'current_timestamp' } },
      { name: 'uid', type: 'UUID', nullable: true, default: { kind: 'expression', value: 'gen_random_uuid()' } },
    ],
    primaryKey: ['id'], indexes: [{ name: 'ix_cliente', columns: ['cliente'] }],
    foreignKeys: [{ name: 'fk_c', columns: ['cliente'], refTable: 'clienti', refColumns: ['nome'], onDelete: 'CASCADE' }],
  });
  assert.equal(statements[0], `CREATE TABLE "app"."ordini" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "cliente" VARCHAR(80) NOT NULL,
  "totale" NUMERIC(10,2) NOT NULL DEFAULT '0',
  "creato" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "uid" UUID NULL DEFAULT gen_random_uuid(),
  PRIMARY KEY ("id"),
  CONSTRAINT "fk_c" FOREIGN KEY ("cliente") REFERENCES "app"."clienti" ("nome") ON DELETE CASCADE
)`);
  assert.deepEqual(statements.slice(1), [
    'CREATE INDEX "ix_cliente" ON "app"."ordini" ("cliente")',
    `COMMENT ON TABLE "app"."ordini" IS 'Ordini'`,
    `COMMENT ON COLUMN "app"."ordini"."cliente" IS 'Nome dell''utente'`,
  ]);
  assert.throws(() => ddl.columnSql({ name: 'a', type: 'INT', unsigned: true }), /unsigned/);
  assert.throws(() => ddl.columnSql({ name: 'a', type: 'TINYINT' }), /type/);
  assert.throws(() => ddl.columnSql({ name: 'a', type: 'TIMESTAMP', onUpdateCurrentTimestamp: true }), /on_update/);
});

test('operazioni del designer: ALTER uniti, rinomine e indici a parte, niente spostamenti', () => {
  const sql = ops.statements('app', [
    { op: 'modify_column', table: 't', name: 'old', column: { name: 'nuovo', type: 'VARCHAR', length: 120, nullable: true } },
    { op: 'add_column', table: 't', column: { name: 'note', type: 'TEXT', nullable: true, comment: 'x' } },
    { op: 'add_index', table: 't', index: { name: 'ix', columns: ['nuovo'], unique: true } },
    { op: 'drop_fk', table: 't', name: 'fk_old' },
  ]);
  assert.deepEqual(sql, [
    'ALTER TABLE "app"."t" RENAME COLUMN "old" TO "nuovo"',
    `ALTER TABLE "app"."t"
  ALTER COLUMN "nuovo" TYPE VARCHAR(120) USING "nuovo"::VARCHAR(120),
  ALTER COLUMN "nuovo" DROP NOT NULL,
  ALTER COLUMN "nuovo" DROP DEFAULT,
  ADD COLUMN "note" TEXT NULL`,
    `COMMENT ON COLUMN "app"."t"."note" IS 'x'`,
    'CREATE UNIQUE INDEX "ix" ON "app"."t" ("nuovo")',
    'ALTER TABLE "app"."t"\n  DROP CONSTRAINT "fk_old"',
  ]);
  const col = (name, extra = {}) => ({ name, type: 'INTEGER', nullable: false, default: { kind: 'none' }, ...extra });
  // l'ordine diverso non è una modifica (PostgreSQL non sposta le colonne); INT e INTEGER sono lo stesso tipo
  const moved = engine.schema.diff({ tables: { t: { columns: [col('a'), col('b')] } } }, { tables: { t: { columns: [col('b'), col('a', { type: 'INT' })] } } });
  assert.deepEqual(moved.ops, []);
});
