// PostgreSQL: DDL dal modello del designer (lo stesso di MySQL: colonne, chiave primaria,
// indici, chiavi esterne, commenti). Nessun SQL arriva dal client: tipi e azioni da elenchi
// ammessi, identificatori tra virgolette, valori come letterali. Indici e commenti in PostgreSQL
// sono istruzioni a sé (CREATE INDEX, COMMENT ON): createTableSql ne restituisce più d'una.

const quoteId = name => '"' + String(name).replace(/"/g, '""') + '"';
const NAME_RE = /^[^\x00]{1,63}$/;

// Letterale SQL di un valore (stringhe con '' raddoppiati: standard_conforming_strings è attivo
// dalla 9.1, i \ non sono escape)
function literal(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE';
  if (typeof v === 'number' || typeof v === 'bigint') return Number.isFinite(Number(v)) ? String(v) : `'${String(v)}'`;
  if (Buffer.isBuffer(v)) return `'\\x${v.toString('hex')}'::bytea`;
  if (v instanceof Date) return `'${v.toISOString()}'`;
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'`;
  return `'${String(v).replace(/\x00/g, '').replace(/'/g, "''")}'`;
}

// tipo → quali parametri accetta
const TYPES = {
  SMALLINT: 'int', INTEGER: 'int', BIGINT: 'int',
  NUMERIC: 'decimal', REAL: 'float', 'DOUBLE PRECISION': 'float',
  VARCHAR: 'length', CHAR: 'length', TEXT: 'plain', BYTEA: 'plain', BOOLEAN: 'plain',
  DATE: 'plain', TIME: 'temporal', TIMESTAMP: 'temporal', TIMESTAMPTZ: 'temporal', INTERVAL: 'plain',
  UUID: 'plain', JSON: 'plain', JSONB: 'plain', INET: 'plain',
};
// nomi equivalenti (anche quelli di information_schema)
const TYPE_ALIASES = {
  INT: 'INTEGER', INT4: 'INTEGER', INT2: 'SMALLINT', INT8: 'BIGINT', DECIMAL: 'NUMERIC', FLOAT4: 'REAL', FLOAT8: 'DOUBLE PRECISION',
  FLOAT: 'DOUBLE PRECISION', BOOL: 'BOOLEAN', 'CHARACTER VARYING': 'VARCHAR', CHARACTER: 'CHAR', BPCHAR: 'CHAR',
  'TIMESTAMP WITHOUT TIME ZONE': 'TIMESTAMP', 'TIMESTAMP WITH TIME ZONE': 'TIMESTAMPTZ', 'TIME WITHOUT TIME ZONE': 'TIME',
};
const canonical = t => { const u = String(t || '').toUpperCase().trim(); return TYPE_ALIASES[u] || u; };
const FK_ACTIONS = new Set(['NO ACTION', 'RESTRICT', 'CASCADE', 'SET NULL', 'SET DEFAULT']);

class DdlError extends Error {
  constructor(key, params = {}) { super(key); this.key = key; this.params = params; }
}
const fail = (key, params) => { throw new DdlError(key, params); };
const int = (v, min, max) => Number.isInteger(Number(v)) && Number(v) >= min && Number(v) <= max;
const empty = v => v === undefined || v === null || v === '';

// Tipo con i suoi parametri: VARCHAR(80), NUMERIC(10,2), TIMESTAMPTZ(3)
function typeSql(c, col) {
  const type = canonical(c.type);
  const kind = TYPES[type];
  if (!kind) fail('type', { ...col, type: String(c.type) });
  if (kind === 'length' && !empty(c.length)) {
    if (!int(c.length, 1, 10485760)) fail('length', col);
    return `${type}(${Number(c.length)})`;
  }
  if (kind === 'decimal' && !empty(c.length)) {
    const p = c.length, s = c.scale ?? 0;
    if (!int(p, 1, 1000) || !int(s, 0, 1000) || Number(s) > Number(p)) fail('precision', col);
    return `${type}(${Number(p)},${Number(s)})`;
  }
  if (kind === 'temporal' && !empty(c.length)) {
    if (!int(c.length, 0, 6)) fail('fraction', col);
    return `${type}(${Number(c.length)})`;
  }
  return type;
}

function defaultSql(c, col) {
  const d = c.default;
  if (!d || !d.kind || d.kind === 'none') return '';
  const kind = TYPES[canonical(c.type)];
  if (d.kind === 'null') { if (!c.nullable) fail('default_null', col); return ' DEFAULT NULL'; }
  if (d.kind === 'current_timestamp') { if (kind !== 'temporal' && canonical(c.type) !== 'DATE') fail('current_timestamp', col); return ' DEFAULT CURRENT_TIMESTAMP'; }
  if (d.kind === 'value') return ` DEFAULT ${literal(String(d.value ?? ''))}`;
  // espressione letta dal database (now(), gen_random_uuid()…): rimessa com'è
  if (d.kind === 'expression') { if (/;/.test(String(d.value))) fail('default', col); return ` DEFAULT ${String(d.value)}`; }
  return fail('default', col);
}

// Definizione di una colonna (il commento è a parte: COMMENT ON COLUMN)
function columnSql(c) {
  if (!c || !NAME_RE.test(c.name || '')) fail('column_name');
  const col = { column: c.name };
  if (c.unsigned) fail('unsigned', col);
  if (c.onUpdateCurrentTimestamp) fail('on_update', col);
  let sql = `${quoteId(c.name)} ${typeSql(c, col)}`;
  if (c.autoIncrement) {
    if (TYPES[canonical(c.type)] !== 'int') fail('auto_increment_type', col);
    sql += ' GENERATED BY DEFAULT AS IDENTITY';
  }
  sql += c.nullable && !c.autoIncrement ? ' NULL' : ' NOT NULL';
  if (!c.autoIncrement) sql += defaultSql(c, col);
  return sql;
}

const columnList = has => (list, where) => {
  if (!Array.isArray(list) || !list.length || !list.every(has)) fail(`columns_${where.what}`, { name: where.name || '' });
  return list.map(quoteId).join(', ');
};

// CREATE [UNIQUE] INDEX "nome" ON "schema"."tabella" ("a", "b")
function indexSql(schema, table, ix, colList) {
  if (!empty(ix.name) && !NAME_RE.test(ix.name)) fail('index_name');
  const name = ix.name || `${table}_${(ix.columns || []).join('_')}_idx`.slice(0, 63);
  return `CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${quoteId(name)} ON ${quoteId(schema)}.${quoteId(table)} (${colList(ix.columns, { what: 'index', name: ix.name })})`;
}

// CONSTRAINT "nome" FOREIGN KEY (…) REFERENCES "schema"."t" (…) ON DELETE … ON UPDATE …
function fkSql(schema, fk, colList) {
  if (!empty(fk.name) && !NAME_RE.test(fk.name)) fail('fk_name');
  if (!NAME_RE.test(fk.refTable || '') || !Array.isArray(fk.refColumns) || !fk.refColumns.every(n => NAME_RE.test(n || ''))) fail('fk_reference');
  if ((fk.refColumns || []).length !== (fk.columns || []).length) fail('fk_count');
  let sql = `${fk.name ? `CONSTRAINT ${quoteId(fk.name)} ` : ''}FOREIGN KEY (${colList(fk.columns, { what: 'foreign_key', name: fk.name })}) REFERENCES ${quoteId(fk.refDatabase || schema)}.${quoteId(fk.refTable)} (${fk.refColumns.map(quoteId).join(', ')})`;
  for (const [k, label] of [['onDelete', 'ON DELETE'], ['onUpdate', 'ON UPDATE']]) {
    if (!fk[k]) continue;
    const action = String(fk[k]).toUpperCase();
    if (!FK_ACTIONS.has(action)) fail('fk_action', { action: String(fk[k]) });
    sql += ` ${label} ${action}`;
  }
  return sql;
}

const commentOnTable = (schema, table, comment) => `COMMENT ON TABLE ${quoteId(schema)}.${quoteId(table)} IS ${comment ? literal(String(comment)) : 'NULL'}`;
const commentOnColumn = (schema, table, column, comment) => `COMMENT ON COLUMN ${quoteId(schema)}.${quoteId(table)}.${quoteId(column)} IS ${comment ? literal(String(comment)) : 'NULL'}`;

// CREATE TABLE con chiave primaria e chiavi esterne, poi gli indici e i commenti: [istruzioni]
function createTableStatements(schema, def) {
  if (!def || !NAME_RE.test(def.name || '')) fail('table_name');
  const cols = Array.isArray(def.columns) ? def.columns : [];
  if (!cols.length) fail('no_columns');
  const names = cols.map(c => c?.name);
  if (new Set(names).size !== names.length) fail('duplicate_columns');
  const colList = columnList(n => names.includes(n));
  const lines = cols.map(columnSql);
  const pk = Array.isArray(def.primaryKey) ? def.primaryKey : [];
  if (pk.length) lines.push(`PRIMARY KEY (${colList(pk, { what: 'primary_key' })})`);
  if (cols.filter(c => c.autoIncrement).length > 1) fail('auto_increment_many');
  for (const fk of def.foreignKeys || []) lines.push(fkSql(schema, fk, colList));
  const out = [`CREATE TABLE ${quoteId(schema)}.${quoteId(def.name)} (\n  ${lines.join(',\n  ')}\n)`];
  for (const ix of def.indexes || []) out.push(indexSql(schema, def.name, ix, colList));
  if (def.comment) out.push(commentOnTable(schema, def.name, def.comment));
  for (const c of cols) if (c.comment) out.push(commentOnColumn(schema, def.name, c.name, c.comment));
  return out;
}

module.exports = {
  quoteId, literal, TYPES, TYPE_ALIASES, canonical, FK_ACTIONS: [...FK_ACTIONS], DdlError, fail, NAME_RE,
  typeSql, columnSql, defaultSql, columnList, indexSql, fkSql, commentOnTable, commentOnColumn, createTableStatements,
  createTableSql: (schema, def) => createTableStatements(schema, def).join(';\n'),
};
